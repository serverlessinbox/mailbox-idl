	g.P("\t\"strings\"")
	g.P("\t\"unicode\"")
	g.P()
	g.P("\t\"google.golang.org/protobuf/encoding/protojson\"")
	g.P("\t\"google.golang.org/protobuf/proto\"")
	g.P(")")
	g.P()

	// Shared helper types (keeps client usable as SDK without extra deps).
	g.P("type BearerTokenProvider interface {")
	g.P("\tBearerToken(ctx context.Context) (string, error)")
	g.P("}")
	g.P()
	g.P("type StaticBearerToken string")
	g.P()
	g.P("func (t StaticBearerToken) BearerToken(ctx context.Context) (string, error) {")
	g.P("\treturn string(t), nil")
	g.P("}")
	g.P()

	g.P("type ClientOption func(*clientOptions)")
	g.P("type clientOptions struct {")
	g.P("\thttpClient    *http.Client")
	g.P("\ttokenProvider BearerTokenProvider")
	g.P("}")
	g.P()

	g.P("func WithHTTPClient(httpClient *http.Client) ClientOption {")
	g.P("\treturn func(o *clientOptions) { o.httpClient = httpClient }")
	g.P("}")
	g.P()
	g.P("func WithBearerToken(token string) ClientOption {")
	g.P("\treturn func(o *clientOptions) { o.tokenProvider = StaticBearerToken(token) }")
	g.P("}")
	g.P()
	g.P("func WithBearerTokenProvider(provider BearerTokenProvider) ClientOption {")
	g.P("\treturn func(o *clientOptions) { o.tokenProvider = provider }")
	g.P("}")
	g.P()

	g.P("func normalizeBaseURL(baseURL string) string {")
	g.P("\treturn strings.TrimSuffix(baseURL, \"/\")")
	g.P("}")
	g.P()

	g.P("func kebabCaseServicePath(serviceName string) string {")
	g.P("\tname := strings.TrimSuffix(serviceName, \"Service\")")
	g.P("\tvar b strings.Builder")
	g.P("\tfor i, r := range name {")
	g.P("\t\tif unicode.IsUpper(r) {")
	g.P("\t\t\tif i != 0 {")
	g.P("\t\t\t\tb.WriteByte('-')")
	g.P("\t\t\t}")
	g.P("\t\t\tb.WriteRune(unicode.ToLower(r))")
	g.P("\t\t\tcontinue")
	g.P("\t\t}")
	g.P("\t\tb.WriteRune(r)")
	g.P("\t}")
	g.P("\treturn \"/\" + b.String()")
	g.P("}")
	g.P()

	g.P("func doProtoJSONCall(ctx context.Context, httpClient *http.Client, tokenProvider BearerTokenProvider, baseURL string, servicePath string, methodName string, req proto.Message, resp proto.Message) error {")
	g.P("\tif httpClient == nil {")
	g.P("\t\thttpClient = &http.Client{}")
	g.P("\t}")
	g.P("\tbaseURL = normalizeBaseURL(baseURL)")
	g.P("\turl := baseURL + servicePath + \"/\" + methodName")
	g.P()
	g.P("\tbody, err := protojson.MarshalOptions{}.Marshal(req)")
	g.P("\tif err != nil {")
	g.P("\t\treturn fmt.Errorf(\"marshal request: %w\", err)")
	g.P("\t}")
	g.P()
	g.P("\thttpReq, err := http.NewRequestWithContext(ctx, http.MethodPost, url, bytes.NewReader(body))")
	g.P("\tif err != nil {")
	g.P("\t\treturn fmt.Errorf(\"build request: %w\", err)")
	g.P("\t}")
	g.P("\thttpReq.Header.Set(\"Content-Type\", \"application/json\")")
	g.P("\tif tokenProvider != nil {")
	g.P("\t\ttoken, err := tokenProvider.BearerToken(ctx)")
	g.P("\t\tif err != nil {")
	g.P("\t\t\treturn fmt.Errorf(\"get bearer token: %w\", err)")
	g.P("\t\t}")
	g.P("\t\tif token != \"\" {")
	g.P("\t\t\thttpReq.Header.Set(\"Authorization\", \"Bearer \"+token)")
	g.P("\t\t}")
	g.P("\t}")
	g.P()
	g.P("\thttpResp, err := httpClient.Do(httpReq)")
