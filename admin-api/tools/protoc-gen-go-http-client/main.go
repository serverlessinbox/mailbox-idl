func generateServiceClient(g *protogen.GeneratedFile, service *protogen.Service) {
	clientName := service.GoName + "Client"
	serviceInterface := service.GoName
	servicePath := "kebabCaseServicePath(\"" + service.GoName + "\")"

	g.P("type ", clientName, " struct {")
	g.P("\tbaseURL       string")
	g.P("\tservicePath   string")
	g.P("\thttpClient    *http.Client")
	g.P("\ttokenProvider BearerTokenProvider")
	g.P("}")
	g.P()

	g.P("func New", clientName, "(baseURL string, opts ...ClientOption) *", clientName, " {")
	g.P("\to := &clientOptions{httpClient: &http.Client{}}")
	g.P("\tfor _, opt := range opts {")
	g.P("\t\tif opt != nil {")
	g.P("\t\t\topt(o)")
	g.P("\t\t}")
	g.P("\t}")
	g.P("\treturn &", clientName, "{")
	g.P("\t\tbaseURL:       normalizeBaseURL(baseURL),")
	g.P("\t\tservicePath:   ", servicePath, ",")
	g.P("\t\thttpClient:    o.httpClient,")
	g.P("\t\ttokenProvider: o.tokenProvider,")
	g.P("\t}")
	g.P("}")
	g.P()

	g.P("var _ ", serviceInterface, " = (*", clientName, ")(nil)")
	g.P()

	for _, method := range service.Methods {
		input := g.QualifiedGoIdent(method.Input.GoIdent)
		output := g.QualifiedGoIdent(method.Output.GoIdent)
		methodName := method.GoName

		g.P("func (c *", clientName, ") ", methodName, "(ctx context.Context, req *", input, ") (*", output, ", error) {")
		g.P("\tif req == nil {")
		g.P("\t\treturn nil, fmt.Errorf(\"request is required\")")
		g.P("\t}")
		g.P("\tresp := &", output, "{}")
		g.P("\tif err := doProtoJSONCall(ctx, c.httpClient, c.tokenProvider, c.baseURL, c.servicePath, \"", methodName, "\", req, resp); err != nil {")
		g.P("\t\treturn nil, err")
		g.P("\t}")
		g.P("\treturn resp, nil")
		g.P("}")
		g.P()
	}
}

